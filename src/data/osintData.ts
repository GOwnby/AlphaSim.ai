export type AssetDomain = 'Maritime' | 'Airspace' | 'Ground' | 'Strategic' | 'Subsurface';
export type AssetModelType =
  | 'carrier'
  | 'destroyer'
  | 'submarine'
  | 'fighter'
  | 'bomber'
  | 'awacs'
  | 'armor'
  | 'sam';

export type TheaterRegion =
  | 'Eastern Europe & Black Sea'
  | 'Middle East & Red Sea'
  | 'Indo-Pacific & Taiwan Strait'
  | 'North Atlantic, Baltic & Arctic'
  | 'Global Strategic Patrol';

export type VerificationTier =
  | 'Live ADS-B / AIS Transponder'
  | 'Confirmed Satellite (SAR / Optical)'
  | 'Official Defense Command Release'
  | 'Multi-Source Geolocated OSINT'
  | 'Google Search Grounded OSINT';

export type TerrainCoverType =
  | 'Open Sea / Airspace'
  | 'Coastal / Littoral Clutter'
  | 'Urban / Fortified Defilade'
  | 'Highland / Mountain Masking';

export interface MilitaryAsset {
  id: string;
  callsign: string;
  designation: string;
  unitClass: string;
  operator: string;
  allegiance:
    | 'NATO / Coalition'
    | 'Russian Federation'
    | 'PLA / China'
    | 'Regional / Non-State'
    | 'Neutral / Monitor';
  domain: AssetDomain;
  modelType: AssetModelType;
  theater: TheaterRegion;
  lat: number;
  lon: number;
  altitudeMeters: number;
  headingDeg: number;
  speedKnots: number;
  combatRadiusKm: number;
  readinessState: 'Combat Action' | 'High-Alert Patrol' | 'Forward Deployed' | 'Transit';
  verification: VerificationTier;
  isLiveTransponder: boolean;
  lastReportedUtc: string;
  lastFixAgeLabel: string;
  publicSourceNote: string;
  personnelEstimate: number;
  armamentSummary: string;
  patrolWaypoints?: Array<[number, number]>;
  // Simulation Wargame Attributes (Who Targets First, Hit %, Terrain Cover)
  terrainCover?: TerrainCoverType;
  firstStrikeInitiative?: number; // 1–100 score determining who acquires & shoots first
  baseHitProbabilityPct?: number; // Base % chance to hit before LOS, terrain & opening-shot modifiers
}

export interface ConflictEvent {
  id: string;
  title: string;
  theater: TheaterRegion;
  category:
    | 'Missile / Drone Salvo'
    | 'Naval Interdiction'
    | 'Airspace Intercept'
    | 'Artillery / Frontline Combat'
    | 'Airstrike / Glide Bomb';
  lat: number;
  lon: number;
  timestampUtc: string;
  severityLevel: 'Critical' | 'High' | 'Elevated';
  verifiedSourcesCount: number;
  citationSummary: string;
  impactAssessment: string;
  // Ordnance Strike Physics & Yield Specifications (for 10–15 min slow 3D sphere expansion)
  ordnanceType: string;
  ordnanceCount: number;
  ordnanceYieldKg: number; // High-Explosive (HE) warhead mass per unit in kg
  dissipationMinutes: number; // 10 to 15 minutes expansion window
  initialElapsedSeconds: number; // Current progress into the 10–15 min window at page load
}

